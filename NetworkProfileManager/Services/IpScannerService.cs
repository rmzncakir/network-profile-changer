using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Net.NetworkInformation;
using System.Net.Sockets;
using System.Runtime.InteropServices;
using System.Threading;
using System.Threading.Tasks;
using NetworkProfileManager.Helpers;
using NetworkProfileManager.Models;

namespace NetworkProfileManager.Services
{
    /// <summary>
    /// Multi-method host discovery. ICMP alone misses a large share of real devices:
    /// Windows blocks echo requests by default in the Public/Domain firewall profiles,
    /// and low-power industrial gear (PLC/HMI/camera/printer) services ICMP at the
    /// lowest priority, so it drops requests under a parallel sweep. This scanner
    /// therefore combines three probes and treats a host as present if ANY succeeds:
    ///
    ///   ARP  — authoritative on the local subnet. A device must answer ARP to speak IP
    ///          at all, and the reply is generated by the stack below the firewall.
    ///   ICMP — fast, and the only thing that yields a real latency figure.
    ///   TCP  — reaches hosts off the local subnet (where ARP does not apply) and
    ///          identifies what the device actually is.
    /// </summary>
    public class IpScannerService
    {
        // ── Win32 ARP ──────────────────────────────────────────────────────────
        // Resolves an IPv4 address to its MAC. Returns NO_ERROR (0) on success.
        // Only meaningful for destinations on a directly attached subnet.
        [DllImport("iphlpapi.dll", ExactSpelling = true)]
        private static extern int SendARP(uint destIp, uint srcIp, byte[] macAddr, ref uint macAddrLen);

        private const int NO_ERROR = 0;

        /// <summary>
        /// Probed TCP ports, ordered by how much the port tells us about the device.
        ///
        /// Deliberately phrased as "protocol (port)" rather than a confident device
        /// claim: a single open port is weak evidence. Port 102, for instance, is the
        /// S7/ISO-TSAP port but is also used by other software, so calling every host
        /// that opens it a Siemens PLC would be wrong — and in a plant that is a
        /// dangerous kind of wrong. OS-level signals (SMB/RDP) come first because a
        /// real PLC does not serve them, so they reliably rule a controller out.
        /// </summary>
        private static readonly (int Port, string Label)[] ProbePorts =
        {
            (3389,  "Windows (RDP)"),
            (445,   "Windows / SMB"),
            (502,   "Modbus TCP (502)"),
            (44818, "EtherNet/IP (44818)"),
            (102,   "S7 / ISO-TSAP (102)"),
            (4840,  "OPC UA (4840)"),
            (554,   "RTSP camera (554)"),
            (9100,  "Printer (9100)"),
            (22,    "SSH (22)"),
            (23,    "Telnet (23)"),
            (443,   "Web (HTTPS)"),
            (80,    "Web (HTTP)"),
            (8080,  "Web (8080)"),
        };

        // ── Public API ─────────────────────────────────────────────────────────

        public Task<List<ScanResult>> ScanRangeAsync(
            string startIp,
            string endIp,
            int timeoutMs   = 1000,
            int maxParallel = 64,
            IProgress<ScanProgress>? progress = null,
            CancellationToken ct = default)
            => ScanRangeAsync(startIp, endIp,
                              new ScanOptions { TimeoutMs = timeoutMs, MaxParallel = maxParallel },
                              progress, ct);

        public Task<List<ScanResult>> ScanRangeAsync(
            string startIp,
            string endIp,
            ScanOptions options,
            IProgress<ScanProgress>? progress = null,
            CancellationToken ct = default)
        {
            const uint MaxHosts = 65536; // one /16 — guards against OOM on a huge range

            uint start = ToUInt(startIp);
            uint end   = ToUInt(endIp);
            if (end < start)
                throw new ArgumentException(
                    Loc.Get("Error.EndIpBeforeStart", "Bitiş IP başlangıçtan küçük olamaz."));

            uint count = end - start + 1;
            if (count > MaxHosts)
                throw new ArgumentException(Loc.Format("Error.ScanRangeTooLarge", MaxHosts));

            var opt = options ?? new ScanOptions();
            // Each worker is a real thread (SendARP blocks), so keep the ceiling modest.
            opt.MaxParallel = Math.Clamp(opt.MaxParallel, 1, 128);
            opt.TimeoutMs   = Math.Clamp(opt.TimeoutMs, 50, 10_000);

            return Task.Run(() => RunScan(start, count, opt, progress, ct), ct);
        }

        // ── Scan loop ──────────────────────────────────────────────────────────

        /// <summary>
        /// Runs the sweep on dedicated threads rather than the thread pool: SendARP is a
        /// blocking call, and dozens of blocked pool threads would trip the pool's slow
        /// thread-injection heuristic and serialize the scan.
        /// </summary>
        private static List<ScanResult> RunScan(
            uint start, uint count, ScanOptions opt,
            IProgress<ScanProgress>? progress, CancellationToken ct)
        {
            int total   = (int)count;
            var queue   = new ConcurrentQueue<uint>();
            for (uint i = 0; i < count; i++) queue.Enqueue(start + i);

            var localSubnets = GetLocalSubnets();
            var results = new ConcurrentBag<ScanResult>();
            int done = 0;

            int workerCount = Math.Min(opt.MaxParallel, total);
            var threads = new List<Thread>(workerCount);

            for (int i = 0; i < workerCount; i++)
            {
                var t = new Thread(() =>
                {
                    while (!ct.IsCancellationRequested && queue.TryDequeue(out uint ipVal))
                    {
                        var r = ProbeHost(ipVal, opt, localSubnets, ct);
                        results.Add(r);
                        int c = Interlocked.Increment(ref done);
                        progress?.Report(new ScanProgress { Current = c, Total = total, Result = r });
                    }
                })
                {
                    IsBackground = true,
                    Name = $"ip-scan-{i}"
                };
                threads.Add(t);
                t.Start();
            }

            foreach (var t in threads) t.Join();
            ct.ThrowIfCancellationRequested();

            return results.OrderBy(r => ToUInt(r.IpAddress)).ToList();
        }

        // ── Per-host probe pipeline ────────────────────────────────────────────

        private static ScanResult ProbeHost(
            uint ipHostOrder, ScanOptions opt,
            List<(uint Network, uint Mask)> localSubnets, CancellationToken ct)
        {
            string ip = ToIpString(ipHostOrder);
            var result = new ScanResult { IpAddress = ip, ScannedAt = DateTime.Now };

            bool isLocal = IsOnLocalSubnet(ipHostOrder, localSubnets);
            bool useArp  = opt.UseArp && isLocal;

            // 1) Fire the first ICMP echo asynchronously so it overlaps the blocking ARP
            //    call below. A dead host then costs max(arp, icmp) instead of their sum,
            //    which roughly halves the time a sweep spends on empty addresses.
            var pingTask = StartPingAsync(ip, opt.TimeoutMs);

            // 2) ARP — authoritative on the local subnet, and answered beneath the
            //    firewall, so it is what surfaces hosts that silently drop ICMP.
            if (useArp && !ct.IsCancellationRequested)
            {
                var mac = TryGetMacViaArp(ipHostOrder);
                if (!string.IsNullOrEmpty(mac))
                {
                    result.MacAddress = mac;
                    result.IsOnline   = true;
                    result.FoundBy    = DiscoveryMethod.Arp;
                }
            }

            // 3) Collect the overlapped ICMP reply — it also gives the only real latency.
            var first = WaitForPing(pingTask);
            if (first is { Status: IPStatus.Success })
            {
                result.ResponseTime = first.RoundtripTime;
                if (!result.IsOnline)
                {
                    result.IsOnline = true;
                    result.FoundBy  = DiscoveryMethod.Icmp;
                }
            }
            else if (!result.IsOnline && !useArp)
            {
                // No ARP verdict available (off-subnet, or ARP disabled), so ICMP is the
                // primary probe here — retry, since weak devices drop the odd echo.
                for (int i = 0; i < Math.Max(0, opt.IcmpRetries) && !ct.IsCancellationRequested; i++)
                {
                    var retry = WaitForPing(StartPingAsync(ip, opt.TimeoutMs));
                    if (retry is { Status: IPStatus.Success })
                    {
                        result.ResponseTime = retry.RoundtripTime;
                        result.IsOnline     = true;
                        result.FoundBy      = DiscoveryMethod.Icmp;
                        break;
                    }
                }
            }

            // 4) TCP probe. Runs when the host is already known (to identify what it is)
            //    or when no ARP verdict was possible and it is still silent.
            bool identify   = result.IsOnline;
            bool lastResort = !result.IsOnline && !useArp;
            if (opt.UseTcpProbe && (identify || lastResort) && !ct.IsCancellationRequested)
            {
                var openPorts = ProbeTcpPorts(ip, opt.TcpTimeoutMs, ct);
                if (openPorts.Count > 0)
                {
                    // ProbePorts is ordered by how much the port reveals, so the first
                    // match is the most informative label for this host.
                    var best = ProbePorts.First(p => openPorts.Contains(p.Port));
                    result.OpenPort   = best.Port;
                    result.DeviceType = best.Label;
                    result.OpenPorts  = string.Join(", ",
                        openPorts.OrderBy(p => p).Select(p => p.ToString(
                            System.Globalization.CultureInfo.InvariantCulture)));

                    if (!result.IsOnline)
                    {
                        result.IsOnline = true;
                        result.FoundBy  = DiscoveryMethod.Tcp;
                    }
                }
            }

            if (result.IsOnline && !ct.IsCancellationRequested)
                result.HostName = TryResolveHost(ip);

            return result;
        }

        // ── Probes ─────────────────────────────────────────────────────────────

        private static string TryGetMacViaArp(uint ipHostOrder)
        {
            try
            {
                var mac = new byte[6];
                uint len = (uint)mac.Length;
                if (SendARP(ToNetworkOrder(ipHostOrder), 0, mac, ref len) != NO_ERROR || len < 6)
                    return "";

                // All-zero means "resolved to nothing" on some stacks.
                if (mac.All(b => b == 0)) return "";

                return string.Join("-", mac.Take(6).Select(b => b.ToString("X2")));
            }
            catch { return ""; }
        }

        /// <summary>
        /// Connects to every probe port in parallel and returns all that accepted. The
        /// ports are probed concurrently, so the whole set costs about one timeout.
        /// </summary>
        private static HashSet<int> ProbeTcpPorts(string ip, int timeoutMs, CancellationToken ct)
        {
            var open = new ConcurrentBag<int>();

            var tasks = ProbePorts.Select(p => Task.Run(async () =>
            {
                try
                {
                    using var client = new TcpClient();
                    var connect = client.ConnectAsync(ip, p.Port);
                    var winner  = await Task.WhenAny(connect, Task.Delay(timeoutMs, ct))
                                            .ConfigureAwait(false);
                    if (winner == connect && !connect.IsFaulted && client.Connected)
                        open.Add(p.Port);
                }
                catch { /* refused / unreachable / cancelled — port simply not open */ }
            })).ToArray();

            try { Task.WaitAll(tasks, timeoutMs + 700); } catch { }

            return open.ToHashSet();
        }

        /// <summary>Starts one ICMP echo without blocking the calling worker thread.</summary>
        private static Task<PingReply?> StartPingAsync(string ip, int timeoutMs)
            => Task.Run(async () =>
            {
                try
                {
                    using var ping = new Ping();
                    return (PingReply?)await ping.SendPingAsync(ip, timeoutMs).ConfigureAwait(false);
                }
                catch { return null; /* unreachable / transient stack error */ }
            });

        private static PingReply? WaitForPing(Task<PingReply?> task)
        {
            try { return task.GetAwaiter().GetResult(); }
            catch { return null; }
        }

        private static string TryResolveHost(string ip)
        {
            try
            {
                // Bound the wait: a missing PTR record can otherwise stall for seconds.
                var task = Dns.GetHostEntryAsync(ip);
                return task.Wait(700) ? task.Result.HostName : "";
            }
            catch { return ""; }
        }

        // ── Local subnet detection ─────────────────────────────────────────────

        private static List<(uint Network, uint Mask)> GetLocalSubnets()
        {
            var list = new List<(uint, uint)>();
            try
            {
                foreach (var nic in NetworkInterface.GetAllNetworkInterfaces())
                {
                    if (nic.OperationalStatus != OperationalStatus.Up) continue;
                    if (nic.NetworkInterfaceType == NetworkInterfaceType.Loopback) continue;

                    foreach (var ua in nic.GetIPProperties().UnicastAddresses)
                    {
                        if (ua.Address.AddressFamily != AddressFamily.InterNetwork) continue;
                        if (ua.IPv4Mask == null) continue;

                        uint addr = ToUInt(ua.Address.ToString());
                        uint mask = ToUInt(ua.IPv4Mask.ToString());
                        if (mask == 0) continue;

                        list.Add((addr & mask, mask));
                    }
                }
            }
            catch { /* enumeration can fail mid-reconfiguration — fall back to "not local" */ }
            return list;
        }

        private static bool IsOnLocalSubnet(uint ip, List<(uint Network, uint Mask)> subnets)
            => subnets.Any(s => (ip & s.Mask) == s.Network);

        // ── Conversions ────────────────────────────────────────────────────────

        /// <summary>Host-order uint → the network-byte-order ULONG that SendARP expects.</summary>
        private static uint ToNetworkOrder(uint hostOrderIp)
            => ((hostOrderIp & 0x000000FFu) << 24)
             | ((hostOrderIp & 0x0000FF00u) << 8)
             | ((hostOrderIp & 0x00FF0000u) >> 8)
             | ((hostOrderIp & 0xFF000000u) >> 24);

        private static uint ToUInt(string ip)
        {
            var parts = ip.Split('.');
            if (parts.Length != 4)
                throw new FormatException(Loc.Format("Error.InvalidIpv4", ip));
            return ((uint)int.Parse(parts[0]) << 24)
                 | ((uint)int.Parse(parts[1]) << 16)
                 | ((uint)int.Parse(parts[2]) <<  8)
                 |  (uint)int.Parse(parts[3]);
        }

        private static string ToIpString(uint ip)
            => $"{(ip >> 24) & 0xFF}.{(ip >> 16) & 0xFF}.{(ip >> 8) & 0xFF}.{ip & 0xFF}";
    }
}
